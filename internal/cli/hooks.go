// copilotSessionStartScript builds the session-start.sh content for GitHub Copilot.
// Copilot passes event JSON on stdin; stdout is ignored. Stats are written to stderr
// so they appear in the terminal for visibility.
func copilotSessionStartScript(notificationPrompt string) string {
	return "#!/usr/bin/env bash\n" +
		"# Generated by: cortex hooks init --copilot\n" +
		"# Regenerate:   cortex hooks init --copilot --force\n" +
		"#\n" +
		"# sessionStart hook: logs available Cortex memories to stderr.\n" +
		"# Copilot passes event JSON on stdin; stdout is ignored by Copilot.\n" +
		"\n" +
		"command -v cortex >/dev/null 2>&1 || exit 0\n" +
		"\n" +
		"STATS=$(cortex stats --json 2>/dev/null || true)\n" +
		`if [ -n "$STATS" ]; then` + "\n" +
		`  SEM=$(printf '%s' "$STATS" | grep -o '"semantic":[[:space:]]*[0-9]*' | grep -o '[0-9]*' || echo 0)` + "\n" +
		`  EPI=$(printf '%s' "$STATS" | grep -o '"episodic":[[:space:]]*[0-9]*' | grep -o '[0-9]*' || echo 0)` + "\n" +
		`  WRK=$(printf '%s' "$STATS" | grep -o '"working":[[:space:]]*[0-9]*' | grep -o '[0-9]*' || echo 0)` + "\n" +
		`  echo "# Cortex Memory: ${SEM} semantic · ${EPI} episodic · ${WRK} working" >&2` + "\n" +
		"  cat >&2 <<'CORTEX_HOOKS_PROMPT_END'\n" +
		notificationPrompt + "\n" +
		"CORTEX_HOOKS_PROMPT_END\n" +
		"fi\n" +
		"\n" +
		"exit 0\n"
}

