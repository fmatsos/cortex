// copilotHooksJSON builds the cortex-hooks.json content for GitHub Copilot.
// scriptsRelDir is the path to the scripts directory relative to the hooks dir (e.g. "scripts").
func copilotHooksJSON(scriptsRelDir string) string {
	startScript := filepath.Join(scriptsRelDir, "session-start.sh")
	endScript := filepath.Join(scriptsRelDir, "session-end.sh")
	return `{
  "version": 1,
  "hooks": {
    "sessionStart": [
      {
        "type": "command",
        "bash": "` + startScript + `",
        "timeoutSec": 30
      }
    ],
    "sessionEnd": [
      {
        "type": "command",
        "bash": "` + endScript + `",
        "timeoutSec": 30
      }
    ]
  }
}
`
}

func runHooksInit(cmd *cobra.Command, args []string) error {
	if hooksInitClaude && hooksInitCopilot {
		return fmt.Errorf("--claude and --copilot are mutually exclusive")
	}

	if hooksInitCopilot {
		return runHooksInitCopilot(cmd)
	}
	return runHooksInitClaude(cmd)
}

func runHooksInitClaude(cmd *cobra.Command) error {
	cfg := config.Global()

	dir := hooksInitDir
	if dir == "" {
		dir = ".claude"
	}

	hooksDir := filepath.Join(dir, "hooks")
	settingsPath := filepath.Join(dir, "settings.json")

	if err := os.MkdirAll(hooksDir, 0755); err != nil {
		return fmt.Errorf("failed to create hooks directory: %w", err)
	}

	scripts := []struct {
		name    string
		content string
	}{
		{"session-start.sh", sessionStartScript(cfg.Hooks.SessionStart.NotificationPrompt)},
		{"session-stop.sh", sessionStopScript(cfg.Hooks.Stop.ReviewPrompt)},
		{"pre-compact.sh", preCompactScript(cfg.Hooks.PreCompact.SummaryPrompt)},
	}

	for _, script := range scripts {
		path := filepath.Join(hooksDir, script.name)
		if !hooksInitForce {
			if _, err := os.Stat(path); err == nil {
				_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  skip   %s (already exists; use --force to overwrite)\n", path)
				continue
			}
		}
		if err := os.WriteFile(path, []byte(script.content), 0755); err != nil {
			return fmt.Errorf("failed to write %s: %w", script.name, err)
		}
		_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", path)
	}

	if !hooksInitForce {
		if _, err := os.Stat(settingsPath); err == nil {
			_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  skip   %s (already exists; use --force to overwrite)\n", settingsPath)
		} else {
			if err := os.WriteFile(settingsPath, []byte(hooksSettingsJSON), 0644); err != nil {
				return fmt.Errorf("failed to write settings.json: %w", err)
			}
			_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", settingsPath)
		}
	} else {
		if err := os.WriteFile(settingsPath, []byte(hooksSettingsJSON), 0644); err != nil {
			return fmt.Errorf("failed to write settings.json: %w", err)
		}
		_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", settingsPath)
	}

	_, _ = fmt.Fprintln(cmd.OutOrStdout(), "\nDone. Commit the generated files to your repository.")
	_, _ = fmt.Fprintln(cmd.OutOrStdout(), "Regenerate anytime with: cortex hooks init --force")
	return nil
}

func runHooksInitCopilot(cmd *cobra.Command) error {
	cfg := config.Global()

	dir := hooksInitDir
	if dir == "" {
		dir = ".github"
	}

	hooksDir := filepath.Join(dir, "hooks")
	scriptsDir := filepath.Join(hooksDir, "scripts")
	hooksJSONPath := filepath.Join(hooksDir, "cortex-hooks.json")

	if err := os.MkdirAll(scriptsDir, 0755); err != nil {
		return fmt.Errorf("failed to create scripts directory: %w", err)
	}

	scripts := []struct {
		name    string
		content string
	}{
		{"session-start.sh", copilotSessionStartScript(cfg.Hooks.SessionStart.NotificationPrompt)},
		{"session-end.sh", copilotSessionEndScript()},
	}

	for _, script := range scripts {
		path := filepath.Join(scriptsDir, script.name)
		if !hooksInitForce {
			if _, err := os.Stat(path); err == nil {
				_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  skip   %s (already exists; use --force to overwrite)\n", path)
				continue
			}
		}
		if err := os.WriteFile(path, []byte(script.content), 0755); err != nil {
			return fmt.Errorf("failed to write %s: %w", script.name, err)
		}
		_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", path)
	}

	if !hooksInitForce {
		if _, err := os.Stat(hooksJSONPath); err == nil {
			_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  skip   %s (already exists; use --force to overwrite)\n", hooksJSONPath)
		} else {
			if err := os.WriteFile(hooksJSONPath, []byte(copilotHooksJSON("scripts")), 0644); err != nil {
				return fmt.Errorf("failed to write cortex-hooks.json: %w", err)
			}
			_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", hooksJSONPath)
		}
	} else {
		if err := os.WriteFile(hooksJSONPath, []byte(copilotHooksJSON("scripts")), 0644); err != nil {
			return fmt.Errorf("failed to write cortex-hooks.json: %w", err)
		}
		_, _ = fmt.Fprintf(cmd.OutOrStdout(), "  write  %s\n", hooksJSONPath)
	}

	_, _ = fmt.Fprintln(cmd.OutOrStdout(), "\nDone. Commit the generated files to your repository.")
	_, _ = fmt.Fprintln(cmd.OutOrStdout(), "Regenerate anytime with: cortex hooks init --copilot --force")
	return nil
}
