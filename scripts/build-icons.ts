#!/usr/bin/env bun
/**
 * Icon pack generator: design/icons.json maps each Cortex icon name to a Phosphor icon, the path data is read from
 * @phosphor-icons/core (MIT) and written into the marked block of site/src/lib/icons.ts.
 *
 *   bun scripts/build-icons.ts           write the block
 *   bun scripts/build-icons.ts --check   exit 1 if the block is stale (writes nothing)
 *
 * Deterministic: same mapping and same Phosphor version in, same bytes out.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const ROOT = resolve(import.meta.dir, "..");
export const TARGET = "site/src/lib/icons.ts";
export const BEGIN = "// <generated-icons>";
export const END = "// </generated-icons>";

export type IconMap = { icons: Record<string, string>; filled: Record<string, string> };

export function loadMap(root = ROOT): IconMap {
  const raw = JSON.parse(readFileSync(join(root, "design/icons.json"), "utf8")) as Partial<IconMap>;
  return { icons: raw.icons ?? {}, filled: raw.filled ?? {} };
}

/** Path of the Phosphor SVG of `name` in `weight` (`light` or `fill`). */
export const phosphorFile = (name: string, weight: "light" | "fill", root = ROOT) =>
  join(root, "node_modules/@phosphor-icons/core/assets", weight, weight === "light" ? `${name}-light.svg` : `${name}-fill.svg`);

const SVG_OPEN = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor">';

/** The inner markup of a Phosphor SVG: only `<path d="..."/>` elements, on the 256 grid, filled with `currentColor`. */
export function innerMarkup(file: string): string {
  const svg = readFileSync(file, "utf8").trim();
  if (!svg.startsWith(SVG_OPEN) || !svg.endsWith("</svg>")) throw new Error(`${file}: unexpected svg root (expected ${SVG_OPEN})`);
  const inner = svg.slice(SVG_OPEN.length, -"</svg>".length);
  if (inner.includes("'") || inner.replace(/<path d="[^"]+"\/>/g, "") !== "") throw new Error(`${file}: only <path d="..."/> elements are supported`);
  return inner;
}

/** The generated block (markers included), one entry per icon in the order of the mapping. */
export function buildBlock(map: IconMap, root = ROOT): string {
  const lines = [
    BEGIN,
    "// Generated by scripts/build-icons.ts from design/icons.json and @phosphor-icons/core (MIT): do not edit, run `bun run icons`.",
    "export const ICONS = {",
  ];
  const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));
  for (const [weight, entries] of [["light", map.icons], ["fill", map.filled]] as const)
    for (const [name, phosphor] of Object.entries(entries)) lines.push(`\t${key(name)}: '${innerMarkup(phosphorFile(phosphor, weight, root))}',`);
  lines.push("} as const;", END);
  return lines.join("\n");
}

/** `source` with its generated block replaced by `block`. */
export function splice(source: string, block: string): string {
  const a = source.indexOf(BEGIN), b = source.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${TARGET}: generated block markers not found`);
  return source.slice(0, a) + block + source.slice(b + END.length);
}

export function expected(root = ROOT): string {
  return splice(readFileSync(join(root, TARGET), "utf8"), buildBlock(loadMap(root), root));
}

export const isStale = (root = ROOT) => !existsSync(join(root, TARGET)) || readFileSync(join(root, TARGET), "utf8") !== expected(root);

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    if (isStale()) {
      console.error(`stale icon pack (run \`bun run icons\`): ${TARGET}`);
      process.exit(1);
    }
    console.log("icon pack is up to date");
  } else {
    writeFileSync(join(ROOT, TARGET), expected());
    console.log(`wrote ${TARGET}`);
  }
}
