#!/usr/bin/env bun
/**
 * Design token generator: design/tokens.json is the single source, the four outputs below are derived from it.
 *
 *   bun scripts/build-design.ts           write the outputs
 *   bun scripts/build-design.ts --check   exit 1 if an output is stale (writes nothing)
 *
 * Deterministic and dependency-free: same tokens in, same bytes out.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

export type Tokens = {
  shared: Record<string, string>;
  light: Record<string, string>;
  dark: Record<string, string>;
  aliases: Record<string, string>;
  print: Record<string, string>;
};

export const ROOT = resolve(import.meta.dir, "..");
export const OUTPUTS = ["site/src/lib/design/tokens.css", "extension/generated/cortex.css", "extension/generated/theme.js", "scripts/generated/cortex-css.ts"] as const;

export function loadTokens(root = ROOT): Tokens {
  return JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8")) as Tokens;
}

/** `{--name}` becomes `var(--name)`; any other value is emitted as is. */
function emit(value: string): string {
  return value.replace(/\{(--[\w-]+)\}/g, "var($1)");
}

const decls = (vars: Record<string, string>, indent: string) => Object.entries(vars).map(([k, v]) => `${indent}${k}: ${emit(v)};\n`).join("");
const rule = (selector: string, body: string, indent = "") => `${indent}${selector} {\n${body}${indent}}\n`;

function header(comment: (text: string) => string): string {
  return comment("Generated by scripts/build-design.ts from design/tokens.json: do not edit, run `bun run design`.") + "\n";
}
const cssComment = (t: string) => `/* ${t} */`;
const lineComment = (t: string) => `// ${t}`;

/** Light block, dark block (prefers-color-scheme only) and the aliases, for a host selector (`:root` or `:host`). */
function plainCss(t: Tokens, host: string): string {
  const light = rule(host, `\tcolor-scheme: light dark;\n${decls(t.light, "\t")}${decls(t.shared, "\t")}${decls(t.aliases, "\t")}`);
  const dark = rule("@media (prefers-color-scheme: dark)", rule(host, `\t\tcolor-scheme: dark;\n${decls(t.dark, "\t\t")}`, "\t"));
  return `${light}\n${dark}`;
}

/** Full theme for the site: system dark, forced dark, forced light, print (black on white whatever the theme). */
function siteCss(t: Tokens): string {
  const light = rule(":root", `\tcolor-scheme: light dark;\n${decls(t.light, "\t")}${decls(t.shared, "\t")}${decls(t.aliases, "\t")}`);
  const darkBody = (indent: string) => `${indent}color-scheme: dark;\n${decls(t.dark, indent)}`;
  const systemDark = rule("@media (prefers-color-scheme: dark)", rule(':root:not([data-theme="light"])', darkBody("\t\t"), "\t"));
  const forcedDark = rule(':root[data-theme="dark"]', darkBody("\t"));
  const forcedLight = rule(':root[data-theme="light"]', "\tcolor-scheme: light;\n");
  // print redefines every themed token: the light palette, with the black-on-white overrides
  const print = rule(
    "@media print",
    rule(':root:not([data-theme="light"]),\n\t:root[data-theme="dark"],\n\t:root[data-theme="light"]', `\t\tcolor-scheme: light;\n${decls({ ...t.light, ...t.print }, "\t\t")}`, "\t"),
  );
  return [light, systemDark, forcedDark, forcedLight, print].join("\n");
}

/** Every generated file, by path relative to the repository root. */
export function buildOutputs(t: Tokens): Record<(typeof OUTPUTS)[number], string> {
  const plain = plainCss(t, ":root");
  const host = plainCss(t, ":host");
  return {
    "site/src/lib/design/tokens.css": header(cssComment) + "\n" + siteCss(t),
    "extension/generated/cortex.css": header(cssComment) + "\n" + plain,
    // classic script (no ESM export): content scripts and Shadow DOM injection read the global
    "extension/generated/theme.js": `${header(lineComment)}globalThis.CORTEX_THEME_CSS = ${JSON.stringify(host)};\n`,
    "scripts/generated/cortex-css.ts": `${header(lineComment)}export const CORTEX_CSS = ${JSON.stringify(plain)};\n`,
  };
}

/** Paths whose content differs from what the tokens produce. */
export function staleOutputs(root = ROOT): string[] {
  const out = buildOutputs(loadTokens(root));
  return OUTPUTS.filter((p) => !existsSync(join(root, p)) || readFileSync(join(root, p), "utf8") !== out[p]);
}

export function writeOutputs(root = ROOT): void {
  const out = buildOutputs(loadTokens(root));
  for (const p of OUTPUTS) {
    mkdirSync(dirname(join(root, p)), { recursive: true });
    writeFileSync(join(root, p), out[p]);
  }
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const stale = staleOutputs();
    if (stale.length) {
      console.error(`stale design outputs (run \`bun run design\`):\n${stale.map((p) => `  ${p}`).join("\n")}`);
      process.exit(1);
    }
    console.log("design outputs are up to date");
  } else {
    writeOutputs();
    console.log(`wrote ${OUTPUTS.length} design outputs`);
  }
}
